"""
Data schemas for the Smart City Zero-Trust IDS.

Defines structured event schemas for device traffic, audit logs,
trust assessments, and incident explanations.
"""

from __future__ import annotations

import time
import uuid
from enum import Enum
from typing import Any, Optional

from pydantic import BaseModel, Field


# ---------------------------------------------------------------------------
# Enums
# ---------------------------------------------------------------------------

class TenantType(str, Enum):
    """Logical tenant partitions within the smart-city simulation."""
    TRAFFIC = "traffic"
    WASTE = "waste"
    WATER = "water"


class DeviceStatus(str, Enum):
    """Operational status of a simulated IoT device."""
    NORMAL = "normal"
    COMPROMISED = "compromised"
    ISOLATED = "isolated"


class PolicyAction(str, Enum):
    """Discrete policy actions issued by the PDP."""
    ALLOW = "allow"
    MONITOR = "monitor"
    RESTRICT = "restrict"
    ISOLATE = "isolate"


class AlertSeverity(str, Enum):
    """Severity levels for dashboard alerts."""
    INFO = "info"
    WARNING = "warning"
    CRITICAL = "critical"


# ---------------------------------------------------------------------------
# Device & Telemetry Schemas
# ---------------------------------------------------------------------------

class DeviceProfile(BaseModel):
    """Static profile for a simulated IoT device."""
    device_id: str = Field(default_factory=lambda: str(uuid.uuid4())[:8])
    name: str
    tenant: TenantType
    device_type: str
    status: DeviceStatus = DeviceStatus.NORMAL

    # Baseline behavior parameters
    normal_packet_rate: float = Field(default=10.0, description="Packets/sec baseline")
    normal_payload_size: float = Field(default=128.0, description="Bytes baseline")
    normal_dest_count: int = Field(default=2, description="Typical unique destinations")


class TelemetryEvent(BaseModel):
    """A single telemetry packet generated by a simulated device."""
    event_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    timestamp: float = Field(default_factory=time.time)
    device_id: str
    tenant: TenantType
    source_ip: str
    dest_ip: str

    # Traffic features
    packet_rate: float = Field(description="Current packets/sec")
    payload_size: float = Field(description="Current payload in bytes")
    dest_count: int = Field(description="Unique destinations in window")
    protocol: str = "MQTT"
    is_encrypted: bool = True

    # Optional attack label (ground truth for evaluation)
    is_attack: bool = False
    attack_type: Optional[str] = None


# ---------------------------------------------------------------------------
# Trust & Policy Schemas
# ---------------------------------------------------------------------------

class TrustAssessment(BaseModel):
    """Output of the ML IDS engine for a single telemetry event."""
    event_id: str
    device_id: str
    tenant: TenantType
    timestamp: float = Field(default_factory=time.time)

    # ML outputs
    anomaly_score: float = Field(ge=0.0, le=1.0, description="0 = normal, 1 = anomalous")
    trust_score: float = Field(ge=0.0, le=1.0, description="1 = fully trusted, 0 = no trust")
    feature_contributions: dict[str, float] = Field(
        default_factory=dict,
        description="Feature name → contribution to anomaly score",
    )

    # Derived action
    recommended_action: PolicyAction = PolicyAction.ALLOW


class PolicyDecision(BaseModel):
    """A decision made by the Policy Decision Point."""
    decision_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    timestamp: float = Field(default_factory=time.time)
    device_id: str
    tenant: TenantType
    event_id: str

    action: PolicyAction
    previous_action: Optional[PolicyAction] = None
    trust_score: float
    anomaly_score: float

    # Explanation
    explanation: str = ""
    evidence: dict[str, Any] = Field(default_factory=dict)


# ---------------------------------------------------------------------------
# Audit & Incident Schemas
# ---------------------------------------------------------------------------

class AuditLogEntry(BaseModel):
    """A structured audit log record for compliance and forensics."""
    log_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    timestamp: float = Field(default_factory=time.time)
    event_type: str  # e.g. "policy_change", "anomaly_detected", "device_isolated"
    severity: AlertSeverity = AlertSeverity.INFO
    tenant: TenantType
    device_id: str

    action: PolicyAction
    explanation: str
    evidence: dict[str, Any] = Field(default_factory=dict)

    # Contextual
    who: str = "PDP-AutoPolicy"
    what: str = ""
    why: str = ""


class IncidentReport(BaseModel):
    """A high-level incident summary combining multiple related events."""
    incident_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    created_at: float = Field(default_factory=time.time)
    resolved_at: Optional[float] = None
    tenant: TenantType
    device_id: str
    severity: AlertSeverity

    description: str
    timeline: list[AuditLogEntry] = Field(default_factory=list)
    root_cause: str = ""
    containment_action: PolicyAction = PolicyAction.ISOLATE
    cross_tenant_impact: bool = False


# ---------------------------------------------------------------------------
# Dashboard / API Schemas
# ---------------------------------------------------------------------------

class DashboardDeviceState(BaseModel):
    """Current state of a device as shown on the dashboard."""
    device_id: str
    name: str
    tenant: TenantType
    status: DeviceStatus
    trust_score: float = 1.0
    current_action: PolicyAction = PolicyAction.ALLOW
    last_event_time: Optional[float] = None
    anomaly_score: float = 0.0


class SystemMetrics(BaseModel):
    """Resource usage metrics for edge monitoring."""
    timestamp: float = Field(default_factory=time.time)
    cpu_percent: float = 0.0
    ram_mb: float = 0.0
    inference_latency_ms: float = 0.0
    events_per_second: float = 0.0
    active_devices: int = 0


class ExperimentResult(BaseModel):
    """Evaluation metrics for a single experiment run."""
    run_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    timestamp: float = Field(default_factory=time.time)
    scenario_name: str
    precision: float = 0.0
    recall: float = 0.0
    f1_score: float = 0.0
    false_positive_rate: float = 0.0
    detection_latency_ms: float = 0.0
    avg_cpu_percent: float = 0.0
    avg_ram_mb: float = 0.0
    notes: str = ""
